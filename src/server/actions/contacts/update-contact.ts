'use server';

import {
  setContactCompanySchema,
  setContactConsentSchema,
  setContactFollowersSchema,
  setContactOwnerSchema,
  setContactTagsSchema,
  updateContactFieldSchema,
} from '@/domain/contacts/mutation-schemas';
import { actionFailure, actionSuccess } from '@/lib/action-result';
import { requireSession } from '@/server/auth/require-session';
import { withTenant } from '@/server/db/with-tenant';
import { handleContactActionError } from '@/server/actions/contacts/handle-contact-action-error';
import { setContactCompany } from '@/server/services/contacts/set-contact-company';
import { setContactConsent } from '@/server/services/contacts/set-contact-consent';
import { setContactFollowers } from '@/server/services/contacts/set-contact-followers';
import { setContactOwner } from '@/server/services/contacts/set-contact-owner';
import { setContactTags } from '@/server/services/contacts/set-contact-tags';
import { updateContactField } from '@/server/services/contacts/update-contact-field';

export async function updateContactFieldAction(input: unknown) {
  let session;
  try {
    session = await requireSession();
  } catch {
    return actionFailure('UNAUTHENTICATED', 'Sign in to continue.');
  }

  const parsed = updateContactFieldSchema.safeParse(input);
  if (!parsed.success) {
    const first = parsed.error.issues[0];
    return actionFailure('VALIDATION_FAILED', first?.message ?? 'Check the form.');
  }

  try {
    const result = await withTenant(session, (tx) =>
      updateContactField(tx, session, parsed.data),
    );
    return actionSuccess(result);
  } catch (error) {
    const mapped = handleContactActionError(error);
    if (mapped) return mapped;
    throw error;
  }
}

